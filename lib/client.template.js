      function onCropDown(e) {
        var p = cropPoint(e)
        cropDrag.current = { x0: p.x, y0: p.y }
        setCropRect({ x: p.x, y: p.y, w: 0, h: 0 })
        try { e.currentTarget.setPointerCapture(e.pointerId) } catch (_) {}
      }
      function onCropMove(e) {
        if (!cropDrag.current) return
        var p = cropPoint(e)
        var d = cropDrag.current
        setCropRect({ x: Math.min(d.x0, p.x), y: Math.min(d.y0, p.y), w: Math.abs(p.x - d.x0), h: Math.abs(p.y - d.y0) })
      }
      function onCropUp() {
        if (!cropDrag.current) return
        cropDrag.current = null
        var r = cropRect
        if (!r || r.w < 0.06 || r.h < 0.06) {
          setCropRect(null)
          runCut({ crop: null })
          return
        }
        runCut({ crop: r })
      }

